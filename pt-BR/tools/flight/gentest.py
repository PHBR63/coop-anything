"""Geração automática de testes: transforma dados de teste reduzidos em um teste de regressão pronto para executar.

Gera na pasta escolhida (padrão tools/flight/regress):
  <name>.json    os dados de teste reduzidos, com "expect": {"converges": true} (o teste passa quando o bug é corrigido)
  <name>.cmake   uma linha add_test() para um caso ctest executar seu programa de reprodução com esses dados
e o executor genérico `python -I tools/flight/regress.py <dir> --replay-cmd "..."` executa todos os conjuntos de dados da pasta.
Dados de teste "cofr-trace-1" (from_failure.py) são reproduzidos no próprio processo por trace_replay.py e não recebem arquivo .cmake.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import trace_replay as TR  # noqa: E402

CMAKE_TEMPLATE = """# generated by tools/flight/gentest.py from a shrunk flight record; do not edit by hand
# Bug it guards against: {sig}
# Steps: {n}. The test passes when the replay program converges (exit code 0) on this fixture.
add_test(NAME cofr_{name}
         COMMAND $<TARGET_FILE:{target}> {flag}${{CMAKE_CURRENT_LIST_DIR}}/{name}.json)
"""


def safe_name(s):
    s = re.sub(r"[^a-z0-9_]+", "_", s.lower()).strip("_")
    return s[:48] or "case"


def generate(shrunk, name, out_dir, target="replay_tool", flag="", expect=None):
    """`target` é o alvo CMake do seu programa de reprodução; `flag`, os argumentos anteriores ao caminho dos dados de teste, por exemplo "--replay ".
    `expect` substitui a expectativa padrão: casos de from_failure.py fixam evidências registradas de uma falha e, portanto, esperam divergência."""
    name = safe_name(name)
    info = shrunk.get("shrunk") or {}
    sig = info.get("signature") or "unknown"
    fx = dict(shrunk)
    fx["expect"] = dict(expect) if expect else {"converges": True, "bug_signature": sig}
    os.makedirs(out_dir, exist_ok=True)
    jp = os.path.join(out_dir, name + ".json")
    cp = os.path.join(out_dir, name + ".cmake")
    with open(jp, "w") as f:
        json.dump(fx, f, indent=1, sort_keys=True)
        f.write("\n")
    if fx.get("format") == TR.FORMAT:
        return [jp]
    key = info.get("list_key") or ("ops" if "ops" in fx and "steps" not in fx else "steps")
    with open(cp, "w") as f:
        f.write(CMAKE_TEMPLATE.format(sig=sig.replace("\n", " "), n=len(fx.get(key, [])), name=name, target=target, flag=flag))
    return [jp, cp]
